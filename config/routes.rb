Rails.application.routes.draw do
  # Reveal health status on /up that returns 200 if the app boots with no exceptions, otherwise 500.
  # Can be used by load balancers and uptime monitors to verify that the app is live.
  get "up" => "rails/health#show", as: :rails_health_check

  # Progressive Web App files rendered from app/views/pwa/*
  get "manifest" => "rails/pwa#manifest", as: :pwa_manifest
  get "service-worker" => "rails/pwa#service_worker", as: :pwa_service_worker

  # Offline fallback shell shown by the service worker when the device is offline.
  get "offline" => "pwa#offline", as: :offline

  # Living style guide for the design system. A development tool, so it is not
  # routed in production at all rather than merely hidden.
  unless Rails.env.production?
    get "design-system" => "design_system#show", as: :design_system
  end

  # Development mailbox. Every email the application sends in development lands
  # here instead of going to a real address. Not mounted in any other
  # environment, so it cannot leak mail contents from a deployed app.
  if Rails.env.development?
    mount LetterOpenerWeb::Engine, at: "/dev/mails", as: :dev_mails
  end

  # ---------------------------------------------------------------- Public

  root "pages#home"

  # -------------------------------------------------------- Authentication

  get  "login"  => "sessions#new",     as: :login
  post "login"  => "sessions#create"
  delete "logout" => "sessions#destroy", as: :logout

  get  "signup" => "registrations#new",  as: :signup
  post "signup" => "registrations#create"

  # Second step of logging in, for accounts with two-factor enabled.
  get  "login/two-factor" => "two_factor_challenges#new", as: :new_two_factor_challenge
  post "login/two-factor" => "two_factor_challenges#create"

  # Password re-entry before a sensitive action ("sudo mode").
  get  "confirm-password" => "reauthentications#new", as: :new_reauthentication
  post "confirm-password" => "reauthentications#create", as: :reauthentications

  # Two-factor enrolment and removal.
  get    "settings/two-factor/new" => "two_factor_settings#new", as: :new_two_factor_settings
  post   "settings/two-factor" => "two_factor_settings#create", as: :two_factor_settings
  delete "settings/two-factor" => "two_factor_settings#destroy"
  get    "settings/recovery-codes" => "recovery_codes#show", as: :recovery_codes
  post   "settings/recovery-codes" => "recovery_codes#create"

  # Password reset. The token is a signed, single-purpose, expiring token
  # generated by the User model rather than a column in the database.
  # The reset token travels as a parameter, never as a path segment: Rails logs
  # the path verbatim and filter_parameters cannot redact part of a path, so a
  # token in the URL ends up in plaintext in every request log.
  get   "passwords/new"  => "passwords#new",    as: :new_password
  post  "passwords"      => "passwords#create", as: :passwords
  get   "passwords/edit" => "passwords#edit",   as: :edit_password
  patch "passwords"      => "passwords#update", as: :password

  # Email verification.
  get  "verify"        => "email_verifications#show", as: :verify_email
  post "verify"        => "email_verifications#create", as: :resend_verification

  # ------------------------------------------------ Authenticated surface

  get "dashboard" => "dashboard#show", as: :dashboard
  resources :strategies do
    member do
      post :start
      post :stop
    end
  end
  # The user's managed MT5 terminal. Singular: a user has one.
  post "terminal/restart" => "terminals#restart", as: :restart_terminal

  get "settings" => "settings#show", as: :settings
  get "profile"  => "profiles#show", as: :profile
  get "activity" => "activity#index", as: :activity
  get "notifications" => "notifications#index", as: :notifications
  get "history" => "trading_history#index", as: :trading_history

  get   "settings/notifications" => "notification_settings#show", as: :notification_settings
  patch "settings/notifications" => "notification_settings#update"

  # The broker account a managed MT5 terminal signs in to. Singular, because a
  # user has one trading account on this platform, not a collection of them.
  get    "settings/broker" => "broker_credentials#edit", as: :edit_broker_credential
  patch  "settings/broker" => "broker_credentials#update", as: :broker_credential
  delete "settings/broker" => "broker_credentials#destroy"

  resources :push_subscriptions, only: %i[create destroy]

  # API tokens the user issues for their MT5 terminal or a mobile device.
  # DELETE revokes (the token stops working but the record remains, so the
  # audit trail still shows what it was). #purge removes the record itself,
  # and is only reachable once a token has been revoked.
  resources :api_tokens, only: %i[index create destroy], path: "settings/api-tokens" do
    member do
      post   :regenerate
      delete :purge
    end
  end

  # ------------------------------------------------------------------ API
  #
  # Versioned from day one so the MT5 Expert Advisor and the future mobile
  # applications consume a stable, namespaced surface.

  namespace :api do
    namespace :v1 do
      get "status" => "status#show"

      # Exchange credentials for a bearer token, and revoke the current one.
      post   "auth/login"  => "auth#create"
      delete "auth/logout" => "auth#destroy"

      get "profile" => "profiles#show"

      resources :strategies, only: %i[index show create update] do
        member do
          post :start
          post :stop
        end
      end

      # Terminal ingestion and read-back. The Expert Advisor writes to
      # trading/report; everything else is read-only for clients and dashboards.
      namespace :trading do
        post "report" => "reports#create"
        get "account" => "account#show"
        get "positions" => "positions#index"
        get "orders" => "orders#index"
        get "history" => "history#index"
      end
    end
  end
end
